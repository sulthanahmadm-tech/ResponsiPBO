package PrakPBO1.PBO1b;

public class Persegi {
    public int hitungLuas(int panjang, int lebar) {
        int luas = panjang * lebar;
        return(luas);
    }

    public int hitungKeliling(int panjang, int lebar) {
        int keliling = 2 * (panjang + lebar);
        return(keliling);
    }
}